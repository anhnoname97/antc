"""Export the checkout's native Umbraco icons for the public portal (no backoffice authentication).

Run from any directory: python tools/Build-UmbracoIconSprite.py
Only trusted repository SVG strings are accepted; never process editor-supplied markup.
"""
import copy
import json
import re
from pathlib import Path
import xml.etree.ElementTree as ET

repo = Path(__file__).resolve().parents[1]
registry = repo / 'src/ANTC.Portal.Core/src/Umbraco.Web.UI.Client/src/packages/core/icon-registry'
web = repo / 'src/ANTC.Portal.App/Umbraco.Web.UI'
namespace = 'http://www.w3.org/2000/svg'
ET.register_namespace('', namespace)
sprite = ET.Element(f'{{{namespace}}}svg')
names = list(dict.fromkeys(re.findall(r'name: "(icon-[a-z0-9-]+)"', (registry / 'icons.ts').read_text(encoding='utf-8-sig'))))
assert names
for name in names:
    source = (registry / 'icons' / f'{name}.ts').read_text(encoding='utf-8-sig')
    match = re.fullmatch(r'\s*export default `(<svg[\s\S]*?</svg>)`;\s*', source)
    assert match and '${' not in source, f'Unsupported icon source: {name}'
    root = ET.fromstring(match[1])
    assert root.tag == f'{{{namespace}}}svg'
    for child in root.iter():
        assert child.tag.split('}')[-1] not in ('script', 'foreignObject', 'image'), name
        assert not any(key.lower().startswith('on') for key in child.attrib), name
    symbol = ET.SubElement(sprite, f'{{{namespace}}}symbol', {'id': name})
    symbol.attrib.update({key: value for key, value in root.attrib.items() if key != 'class'})
    for child in root:
        symbol.append(copy.deepcopy(child))

destination = web / 'wwwroot/assets/icons'
destination.mkdir(parents=True, exist_ok=True)
ET.indent(sprite, space='  ')
(destination / 'umbraco.svg').write_text(
    '<!-- Generated from the native Umbraco icon registry. See Umbraco-LICENSE.txt. -->\n' + ET.tostring(sprite, encoding='unicode') + '\n', encoding='utf-8')
(destination / 'Umbraco-LICENSE.txt').write_text((repo / 'src/ANTC.Portal.Core/LICENSE.md').read_text(encoding='utf-8-sig'), encoding='utf-8')
catalog = '''// Generated by tools/Build-UmbracoIconSprite.py from the native Umbraco registry.
using System.Collections.Frozen;

namespace Umbraco.Web.UI.Models;

public static class UmbracoIconCatalog
{
    public static readonly FrozenSet<string> Names = new[]
    {
'''
catalog += ''.join(f'        {json.dumps(name)},\n' for name in names)
catalog += '''    }.ToFrozenSet(StringComparer.Ordinal);
}
'''
(web / 'Models/UmbracoIconCatalog.cs').write_text(catalog, encoding='utf-8')
print(f'Exported {len(names)} native Umbraco icons and the portal name catalog.')
